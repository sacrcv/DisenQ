"""Frozen text encoder producing the language supervision T_b / T_m / T_b_hat.

The paper uses BERT as a *frozen* pre-trained text encoder for the three
structured prompts generated by the VLM (Section 3.1).
"""

from typing import Dict, List, Sequence

import torch
import torch.nn as nn

from disenq.utils.logger import get_logger


class FrozenTextEncoder(nn.Module):
    """Tokenise and encode prompt strings with a frozen BERT.

    Returns token-level hidden states (not a pooled vector) because DisenQ
    cross-attends over the concatenation ``[F, T_x]`` (Eq. 1-3), so the text
    needs to stay a sequence.
    """

    def __init__(
        self,
        model_name: str = "bert-base-uncased",
        max_length: int = 48,
        local_files_only: bool = False,
    ):
        super().__init__()
        from transformers import AutoModel, AutoTokenizer

        self.tokenizer = AutoTokenizer.from_pretrained(
            model_name, local_files_only=local_files_only
        )
        self.encoder = AutoModel.from_pretrained(model_name, local_files_only=local_files_only)
        self.encoder.eval()
        for param in self.encoder.parameters():
            param.requires_grad = False

        self.max_length = max_length
        self.width = self.encoder.config.hidden_size
        get_logger().info(
            f"built frozen text encoder '{model_name}' (width={self.width}, "
            f"max_length={max_length})"
        )

    def train(self, mode: bool = True):
        """Keep the frozen encoder in eval mode regardless of the parent's mode."""
        super().train(mode)
        self.encoder.eval()
        return self

    @property
    def device(self) -> torch.device:
        return next(self.encoder.parameters()).device

    def tokenize(self, texts: Sequence[str]) -> Dict[str, torch.Tensor]:
        return self.tokenizer(
            list(texts),
            padding="max_length",
            truncation=True,
            max_length=self.max_length,
            return_tensors="pt",
        )

    @torch.no_grad()
    def forward(self, texts: Sequence[str], device: torch.device = None):
        """Encode a batch of strings.

        Returns:
            ``(hidden_states [B, L, width], attention_mask [B, L])``.
        """
        device = device or self.device
        tokens = self.tokenize(texts)
        tokens = {k: v.to(device) for k, v in tokens.items()}
        out = self.encoder(**tokens)
        return out.last_hidden_state, tokens["attention_mask"]

    @torch.no_grad()
    def encode_branches(
        self, prompts: Dict[str, List[str]], device: torch.device = None
    ) -> Dict[str, Dict[str, torch.Tensor]]:
        """Encode the three prompt categories in one padded batch.

        Args:
            prompts: ``{"biometrics": [...], "motion": [...],
                "non_biometrics": [...]}`` each of length ``B``.

        Returns:
            ``{branch: {"features": [B, L, width], "mask": [B, L]}}``.
        """
        branches = list(prompts.keys())
        flat: List[str] = []
        for branch in branches:
            flat.extend(prompts[branch])

        features, mask = self.forward(flat, device=device)
        chunk = features.shape[0] // len(branches)
        out = {}
        for i, branch in enumerate(branches):
            sl = slice(i * chunk, (i + 1) * chunk)
            out[branch] = {"features": features[sl], "mask": mask[sl]}
        return out
